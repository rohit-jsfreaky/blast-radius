import { run, J, errs } from "./lib.mjs";
await run("f19-reservation-revision-history", "`seq` starts at 1 and increases by exactly 1", async (call, h) => {
  const e = errs();
  const k = "rev-create";
  const body = { table_id: "t_2", starts_at_local: "2027-09-23T19:00", party_size: 2 };
  const c = await h.book(body, "ada", k);
  e.check(c.s === 201 && c.b.revision === 1 && c.b.accepted_terms?.policy_version === 0, `create revision/terms ${J(c.b)}`);
  const ref = c.b.reference;
  let H = (await h.hist(ref)).b;
  e.check(J(H?.entries?.map((x) => [x.seq, x.event, x.revision])) === J([[1, "created", 1]]), `history after create ${J(H)}`);
  e.check(J(H?.entries?.[0]?.changes) === J([{ field: "table_id", from: null, to: "t_2" }, { field: "starts_at_local", from: null, to: "2027-09-23T19:00" }, { field: "party_size", from: null, to: 2 }]), `created changes ${J(H?.entries?.[0]?.changes)}`);
  const p = await h.patch(ref, { party_size: 3, starts_at_local: "2027-09-23T20:00" });
  e.check(p.s === 200 && p.b.revision === 2, `real patch revision ${p.s} ${p.b?.revision}`);
  const noop = await h.patch(ref, { party_size: 3, table_id: "t_2" });
  e.check(noop.s === 200 && noop.b.revision === 2, `no-op patch ${noop.s} rev ${noop.b?.revision}`);
  const x1 = await h.cancel(ref); const x2 = await h.cancel(ref);
  e.check(x1.b?.revision === 3 && x2.s === 200 && x2.b?.revision === 3, `cancel revisions ${x1.b?.revision}/${x2.b?.revision}`);
  H = (await h.hist(ref)).b;
  e.check(J(H.entries.map((x) => [x.seq, x.event, x.revision])) === J([[1, "created", 1], [2, "changed", 2], [3, "cancelled", 3]]), `history ${J(H.entries.map((x) => [x.seq, x.event, x.revision]))}`);
  e.check(J(H.entries[1].changes) === J([{ field: "starts_at_local", from: "2027-09-23T19:00", to: "2027-09-23T20:00" }, { field: "party_size", from: 2, to: 3 }]), `changed entry ${J(H.entries[1].changes)}`);
  e.check(J(H.entries[2].changes) === "[]", "cancelled changes not empty");
  e.check(H.entries.every((x) => x.accepted_terms && typeof x.at === "string" && /[+-]\d\d:\d\d$|Z$/.test(x.at)), "entries lack terms or offset `at`");
  const r = await h.book(body, "ada", k);
  e.check(r.s === 200 && J(r.b) === J(c.b), `replay not original ${r.s} rev ${r.b?.revision}`);
  e.check((await h.hist(ref)).b.entries.length === 3, "replay recorded history");
  const d = await call("GET", `/reservations/${ref}/decision`, undefined, h.auth(await h.login()));
  e.check(d.s === 200 && d.b.revision === 3 && d.b.reference === ref && d.b.accepted_terms, `decision ${J(d.b)}`);
  return e.result();
});
